"""Order-independent policy noise through public openpi APIs; no upstream edits."""

from __future__ import annotations

from sgvla.eval.manifest import PROTOCOL

RNG_KEY = "__sgvla_rng__"


class SeededPolicy:
    def __init__(self, policy):
        self.policy = policy

    @property
    def metadata(self):
        return self.policy.metadata

    def infer(self, observation):
        observation = dict(observation)
        request = observation.pop(RNG_KEY, None)
        if request is None:
            return self.policy.infer(observation)
        if (
            request.get("protocol") != PROTOCOL
            or type(request.get("seed")) is not int
            or not 0 <= request["seed"] < 2**32
            or type(request.get("call")) is not int
            or not 0 <= request["call"] < 2**32
        ):
            raise ValueError("Invalid seeded policy request")
        if "noise" in request:
            raise ValueError("Noise must be generated by the pinned server adapter")
        import jax
        import numpy as np

        key = jax.random.fold_in(jax.random.key(request["seed"]), request["call"])
        noise = np.asarray(jax.random.normal(key, (50, 32)))
        return self.policy.infer(observation, noise=noise)


class SeededClient:
    def __init__(self, client, seed):
        metadata = client.get_server_metadata().get("sgvla", {})
        if metadata.get("rng_protocol") != PROTOCOL:
            raise RuntimeError("Server lacks seeded-noise support; restart it with the new adapter")
        self.client, self.seed, self.call = client, seed, 0

    def infer(self, observation):
        request = {"protocol": PROTOCOL, "seed": self.seed, "call": self.call}
        result = self.client.infer({**observation, RNG_KEY: request})
        self.call += 1
        return result

    def get_server_metadata(self):
        return self.client.get_server_metadata()
